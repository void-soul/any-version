/// 将后端返回的中文错误消息翻译为英文；识别不到时原样返回。
export function translateBackendError(msg: string): string {
  if (!msg) return msg;
  const exact = STATIC_ERRORS[msg.trim()];
  if (exact) return exact;
  for (const { re, to } of PATTERN_ERRORS) {
    const m = msg.match(re);
    if (m) return msg.replace(re, to);
  }
  return msg;
}

// 当前界面语言获取器：由 i18n 初始化时注册（避免 backendErrors 与 i18n 循环依赖）。
let currentLangGetter: () => string = () => "zh";

/** 注册界面语言获取器（i18n 初始化时调用；语言切换后由同一闭包返回最新值）。 */
export function installBackendErrorI18n(getLang: () => string): void {
  currentLangGetter = getLang;
}

/** 英文界面下把后端中文错误消息翻译为英文；非英文界面原样返回。 */
export function translateErrorIfEn(msg: string): string {
  try {
    if (currentLangGetter().startsWith("en")) {
      return translateBackendError(msg);
    }
  } catch {
    /* 语言读取失败时按中文处理 */
  }
  return msg;
}