/**
 * 表配色预设（点一下取消；不选 = 用模块强调色）。
 *
 * 单独成模块的原因：它有两个消费方，而其中一个是要被单测钉住的纯数据 ——
 * 放在面板里测就得把整个面板（含 i18n / Tauri 依赖）拖进测试环境。
 *
 * 两个用途：
 *   1. 选中表时的「颜色」点选（12 个色点）
 *   2. 同系列自动配色：按系列出现顺序依次取色（`assignSeriesColors`）
 *
 * 顺序是按「相邻两色差得开」排的 —— 自动配色会**连续取用**，相邻色若相近，
 * 挨着的两个系列就会糊成一片，失去「按色分系列」的意义。差异最小的靛蓝/紫罗兰
 * 刻意压到最后。全部取 Tailwind 500 档：深色画布上足够亮，也能当霓虹环的底色。
 */
export const NODE_COLORS = [
  "#0ea5e9", // 天蓝
  "#f59e0b", // 琥珀
  "#a855f7", // 紫
  "#22c55e", // 绿
  "#ef4444", // 红
  "#3b82f6", // 蓝
  "#f97316", // 橙
  "#14b8a6", // 青绿
  "#d946ef", // 品红
  "#84cc16", // 黄绿
  "#6366f1", // 靛蓝
  "#8b5cf6", // 紫罗兰
];

/**
 * 该颜色是否来自预设色板。
 *
 * 用途：预设色的交互是「再点一次同一个圆点 = 取消」，而自定义色没有这个等价操作，
 * 所以界面要靠它区分「当前是预设色还是自定义色」，后者才需要补一个清除按钮。
 */
export function isPresetColor(color?: string | null): boolean {
  return !!color && NODE_COLORS.includes(color);
}
